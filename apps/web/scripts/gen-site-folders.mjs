// Generates lib/site-folders.ts — the set of brand folders that have a real
// static website under public/sites. Runs automatically before every build
// (see the "prebuild" script in package.json), so adding a new brand site is
// still zero-touch: drop the folder under public/sites and rebuild.
import { readdirSync, statSync, writeFileSync, existsSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sitesDir = path.join(root, "public", "sites");
const outFile = path.join(root, "lib", "site-folders.ts");

let folders = [];
if (existsSync(sitesDir)) {
  folders = readdirSync(sitesDir)
    .filter((name) => {
      try {
        return (
          statSync(path.join(sitesDir, name)).isDirectory() &&
          existsSync(path.join(sitesDir, name, "index.html"))
        );
      } catch {
        return false;
      }
    })
    .sort();
}

const body = `// AUTO-GENERATED by scripts/gen-site-folders.mjs — do not edit by hand.
// Brand folders under public/sites that contain a static index.html.
export const SITE_FOLDERS = new Set<string>(${JSON.stringify(folders, null, 2)});
`;

writeFileSync(outFile, body);
console.log(`[gen-site-folders] wrote ${folders.length} folders to lib/site-folders.ts`);
