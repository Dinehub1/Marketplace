#!/usr/bin/env node
/**
 * Regenerates apps/mobile/plugins/skadnetwork-ids.json from the networks' own lists.
 *
 * iOS attributes an ad install only to a network whose SKAdNetwork id is in the app's
 * Info.plist. A bidder that is missing from the list still bids, but its advertisers
 * cannot measure installs from our inventory, so they bid less for it — a silent eCPM
 * loss, never an error. Every network in the AdMob auction therefore needs its ids here.
 *
 * Sources (the ones each network's AdMob adapter guide points at):
 *   - Google:   https://developers.google.com/admob/ios/3p-skadnetworks (HTML; ids scraped)
 *   - AppLovin: https://skadnetwork-ids.applovin.com/v1/skadnetworkids.json
 *   - InMobi:   https://www.inmobi.com/skadnetworkids.json
 *
 * The output is committed, so a build never depends on these hosts being up. Re-run
 * when a network is added, or every few months as the lists grow:
 *
 *   node scripts/sync-skadnetwork-ids.mjs
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "apps/mobile/plugins/skadnetwork-ids.json");
const ID = /^[a-z0-9]{10}\.skadnetwork$/;

/** Google's own id; stated in the AdMob iOS privacy docs, and first in the list. */
const GOOGLE_ID = "cstr6suwn9.skadnetwork";

async function fetchText(url) {
  const res = await fetch(url, { redirect: "follow" });
  if (!res.ok) throw new Error(`${url} answered ${res.status}`);
  return res.text();
}

async function fromJson(url) {
  const body = JSON.parse(await fetchText(url));
  return (body.skadnetwork_ids ?? []).map((e) => String(e.skadnetwork_id ?? "").trim().toLowerCase());
}

async function fromGoogle() {
  const html = await fetchText("https://developers.google.com/admob/ios/3p-skadnetworks");
  return [GOOGLE_ID, ...(html.match(/[a-z0-9]{10}\.skadnetwork/g) ?? [])];
}

const sources = {
  google: await fromGoogle(),
  applovin: await fromJson("https://skadnetwork-ids.applovin.com/v1/skadnetworkids.json"),
  inmobi: await fromJson("https://www.inmobi.com/skadnetworkids.json"),
};

// A source that returns nothing has changed format; writing a shorter list would
// silently drop that network's buyers, so stop instead.
for (const [name, ids] of Object.entries(sources)) {
  if (ids.filter((id) => ID.test(id)).length < 5) {
    throw new Error(`${name}: fewer than 5 ids parsed — the source changed format; not writing.`);
  }
}

const ids = [...new Set(Object.values(sources).flat().filter((id) => ID.test(id)))];
writeFileSync(
  OUT,
  JSON.stringify(
    {
      _comment: "Generated by scripts/sync-skadnetwork-ids.mjs — do not edit by hand.",
      generatedAt: new Date().toISOString().slice(0, 10),
      counts: Object.fromEntries(Object.entries(sources).map(([k, v]) => [k, new Set(v).size])),
      ids,
    },
    null,
    2,
  ) + "\n",
);
console.log(`wrote ${ids.length} ids to ${OUT}`, Object.fromEntries(Object.entries(sources).map(([k, v]) => [k, new Set(v).size])));
